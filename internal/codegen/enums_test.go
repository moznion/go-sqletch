// Design 26: PostgreSQL enums map to a generated named string type.

var (
	eventKindExt = &dialect.TypeExt{Schema: "public", Kind: dialect.TypeKindEnum,
		Labels: []string{"QUEUED", "STARTED", "in-progress", "済"}}
	eventKind = dialect.TypeRef{OID: 16400, Name: "event_kind", Ext: eventKindExt}
	int8Type  = dialect.TypeRef{OID: 20, Name: "int8"}
)

const enumInsert = `-- name: InsertEvent :exec
INSERT INTO ev (kind, maybe) VALUES (:kind, :maybe);
`

const enumList = `-- name: ListEvents :many
SELECT id, kind, maybe FROM ev
WHERE TRUE
@if-present(kind)
  AND kind = :kind
@endif
ORDER BY id
LIMIT :limit;
`

func enumInput(t *testing.T, src string, params map[string]dialect.TypeRef, cols []dialect.ColumnDesc, nullableCols []bool, nullableParams map[string]bool) QueryInput {
	t.Helper()
	q := scanOne(t, src)
	return QueryInput{Q: q, Frags: BuildFrags(postgres.Profile{}, q), ParamTypes: params,
		Columns: cols, Nullable: nullableCols, NullableParams: nullableParams}
}

func enumInputs(t *testing.T) []QueryInput {
	list := enumInput(t, enumList, map[string]dialect.TypeRef{"kind": eventKind, "limit": int8Type},
		[]dialect.ColumnDesc{
			{Name: "id", Type: int8Type},
			{Name: "kind", Type: eventKind},
			{Name: "maybe", Type: eventKind},
		}, []bool{false, false, true}, nil)
	list.Q.Params["kind"].Optional = true // the pipeline's guard analysis sets it
	return []QueryInput{
		enumInput(t, enumInsert, map[string]dialect.TypeRef{"kind": eventKind, "maybe": eventKind}, nil, nil,
			map[string]bool{"maybe": true}),
		list,
	}
}

func generateEnums(t *testing.T, in []QueryInput) (map[string][]byte, []diagnostics.Diagnostic) {
	t.Helper()
	return Generate(Options{Package: "gen", Style: runtime.StyleDollar}, postgres.TypeMap{}, in)
}

func TestGenerate_EnumParamsAndColumns(t *testing.T) {
	files, diags := generateEnums(t, enumInputs(t))
	if len(diags) != 0 {
		t.Fatalf("diagnostics: %+v", diags)
	}
	assertPatterns(t, string(files["insert_event.sql.gen.go"]),
		`Kind\s+EventKind\b`,
		`Maybe\s+optional\.Option\[EventKind\]`, // design 20 nullable value param
	)
	assertPatterns(t, string(files["list_events.sql.gen.go"]),
		`Kind\s+sqletch\.Omittable\[EventKind\]`, // guarded
		`Kind\s+EventKind\b`,                     // NOT NULL column
		`Maybe\s+optional\.Option\[EventKind\]`,  // nullable column
	)
	// Declared ONCE for the package, labels in the oracle's order.
	want := `// Code generated by sqletch. DO NOT EDIT.

package gen

// EventKind is the database enum public.event_kind. Its values are the enum's labels;
// the database rejects any other value when it is bound.
type EventKind string

const (
	EventKindQueued     EventKind = "QUEUED"
	EventKindStarted    EventKind = "STARTED"
	EventKindInProgress EventKind = "in-progress"
	EventKind済          EventKind = "済"
)
`
	if got := string(files["enums.gen.go"]); got != want {
		t.Fatalf("enums.gen.go:\n%s\nwant:\n%s", got, want)
	}
	for name, src := range files {
		if name != "enums.gen.go" && strings.Contains(string(src), "type EventKind ") {
			t.Errorf("%s redeclares EventKind", name)
		}
	}
}

// No enum referenced ⇒ no enums.gen.go: existing packages regenerate
// byte-identically.
func TestGenerate_NoEnumsNoFile(t *testing.T) {
	files, diags := generateEnums(t, []QueryInput{enumInput(t, `-- name: GetOne :one
SELECT id FROM ev WHERE id = :id;
`, map[string]dialect.TypeRef{"id": int8Type}, []dialect.ColumnDesc{{Name: "id", Type: int8Type}}, []bool{false}, nil)})
	if len(diags) != 0 {
		t.Fatalf("diagnostics: %+v", diags)
	}
	if _, ok := files["enums.gen.go"]; ok {
		t.Fatal("enums.gen.go emitted with no enum referenced")
	}
}

// D5: only enums are mapped; every other unmapped type is still
// SQLETCH311 — arrays of enums, domains, composite types, and
// unmapped built-ins alike.
func TestGenerate_NonEnumUnmappedStill311(t *testing.T) {
	for _, tr := range []dialect.TypeRef{
		{OID: 16399, Name: "_event_kind", Ext: &dialect.TypeExt{Schema: "public", Kind: "b"}},
		{OID: 16420, Name: "posint", Ext: &dialect.TypeExt{Schema: "public", Kind: "d"}},
		{OID: 16430, Name: "pair", Ext: &dialect.TypeExt{Schema: "public", Kind: "c"}},
		{OID: 1186, Name: "interval"},
		{OID: 16400, Name: "event_kind"}, // enum OID without Ext: never guessed
	} {
		t.Run(tr.Name, func(t *testing.T) {
			_, diags := generateEnums(t, []QueryInput{enumInput(t, enumInsert,
				map[string]dialect.TypeRef{"kind": tr, "maybe": eventKind}, nil, nil, nil)})
			if !hasCode(diags, diagnostics.CodeUnsupportedType) {
				t.Fatalf("want SQLETCH311, got %+v", diags)
			}
		})
	}
}

// D6 and the package-level name space: every enum name must be new.
func TestGenerate_EnumNameCollisions(t *testing.T) {
	other := dialect.TypeRef{OID: 16500, Name: "event_kind",
		Ext: &dialect.TypeExt{Schema: "audit", Kind: dialect.TypeKindEnum, Labels: []string{"X"}}}
	enumOf := func(name string, labels ...string) dialect.TypeRef {
		return dialect.TypeRef{OID: 16600, Name: name,
			Ext: &dialect.TypeExt{Schema: "public", Kind: dialect.TypeKindEnum, Labels: labels}}
	}
	for _, tc := range []struct {
		name string
		in   func(t *testing.T) []QueryInput
		code diagnostics.Code
	}{
		{"same name in two schemas", func(t *testing.T) []QueryInput {
			return []QueryInput{
				enumInput(t, enumInsert, map[string]dialect.TypeRef{"kind": eventKind, "maybe": other}, nil, nil, nil),
			}
		}, diagnostics.CodeNameCollision},
		{"same name in two schemas across queries", func(t *testing.T) []QueryInput {
			in := enumInputs(t)
			in[1].ParamTypes["kind"] = other
			return in
		}, diagnostics.CodeNameCollision},
		{"type name = a query's Row type", func(t *testing.T) []QueryInput {
			in := enumInputs(t)
			in[0].ParamTypes["kind"] = enumOf("list_events_row", "A")
			return in
		}, diagnostics.CodeNameCollision},
		{"constant = a @choose constant", func(t *testing.T) []QueryInput {
			q := enumInput(t, `-- name: Pick :many
SELECT id FROM ev WHERE kind = :kind
@choose(sort)
@case(asc)
ORDER BY id ASC
@default
ORDER BY id DESC
@end
LIMIT 10;
`, map[string]dialect.TypeRef{"kind": enumOf("pick_sort", "asc")},
				[]dialect.ColumnDesc{{Name: "id", Type: int8Type}}, []bool{false}, nil)
			return []QueryInput{q}
		}, diagnostics.CodeNameCollision},
		{"fixed package name", func(t *testing.T) []QueryInput {
			return []QueryInput{enumInput(t, enumInsert,
				map[string]dialect.TypeRef{"kind": enumOf("queries", "A"), "maybe": eventKind}, nil, nil, nil)}
		}, diagnostics.CodeInvalidColumnIdentifier},
		{"type name is not an exported identifier", func(t *testing.T) []QueryInput {
			return []QueryInput{enumInput(t, enumInsert,
				map[string]dialect.TypeRef{"kind": enumOf("状態", "A"), "maybe": eventKind}, nil, nil, nil)}
		}, diagnostics.CodeInvalidColumnIdentifier},
	} {
		t.Run(tc.name, func(t *testing.T) {
			files, diags := generateEnums(t, tc.in(t))
			if !hasCode(diags, tc.code) || !diagnostics.HasErrors(diags) {
				t.Fatalf("want error %s, got %+v", tc.code, diags)
			}
			if hasCode(diags, diagnostics.CodeUnsupportedType) {
				t.Errorf("a named enum must not also be reported as SQLETCH311: %+v", diags)
			}
			if _, ok := files["enums.gen.go"]; ok {
				t.Error("enums.gen.go emitted despite errors")
			}
		})
	}
}

// D2: labels without distinct identifiers ⇒ the type without constants,
// a SQLETCH320 WARNING, and the package is still generated.
func TestGenerate_EnumLabelsWithoutIdentifiers(t *testing.T) {
	in := enumInputs(t)
	odd := dialect.TypeRef{OID: 16700, Name: "status",
		Ext: &dialect.TypeExt{Schema: "public", Kind: dialect.TypeKindEnum, Labels: []string{"in-progress", "in_progress", "done"}}}
	in[0].ParamTypes["kind"] = odd
	files, diags := generateEnums(t, in)
	if diagnostics.HasErrors(diags) || !hasCode(diags, diagnostics.CodeEnumLabelIdent) {
		t.Fatalf("want only a SQLETCH320 warning, got %+v", diags)
	}
	if !strings.Contains(diags[0].Message, `"in-progress", "in_progress"`) {
		t.Errorf("warning must name the colliding labels: %s", diags[0].Message)
	}
	src := string(files["enums.gen.go"])
	if !strings.Contains(src, "type Status string") || strings.Contains(src, "StatusDone") {
		t.Fatalf("Status must be declared without constants:\n%s", src)
	}
	if !strings.Contains(src, "EventKindQueued") {
		t.Errorf("an unaffected enum keeps its constants:\n%s", src)
	}
	if _, ok := files["insert_event.sql.gen.go"]; !ok {
		t.Error("a warning must not drop the query's file")
	}
}

func TestEnumConstNames(t *testing.T) {
	for _, tc := range []struct {
		labels []string
		want   []string // nil = no constants
	}{
		{[]string{"STARTED", "ANSWERED"}, []string{"KStarted", "KAnswered"}},
		{[]string{"in-progress", "on hold", "user_id"}, []string{"KInProgress", "KOnHold", "KUserID"}},
		{[]string{"済", "1st", "ü"}, []string{"K済", "K1st", "KÜ"}},
		{[]string{"x1st", "1st"}, []string{"KX1st", "K1st"}}, // no spurious X
		{[]string{"a", "A"}, nil},
		{[]string{"in-progress", "in_progress"}, nil},
		{[]string{"ok", "--"}, nil},
		{[]string{"ok", ""}, nil},
	} {
		got, bad := enumConstNames("K", tc.labels)
		if !slices.Equal(got, tc.want) || (tc.want == nil) != (bad != nil) {
			t.Errorf("enumConstNames(%q) = %q (bad %q), want %q", tc.labels, got, bad, tc.want)
		}
	}
}

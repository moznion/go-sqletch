// enumType is one database enum a package's queries reference (design
// 26 §4.4): declared once for the package in enums.gen.go, shared by
// every query that binds or scans it — the policy.gen.go pattern.
type enumType struct {
	goName string
	schema string
	name   string
	labels []string
	query  string // first referencing query (sorted order), for diagnostics
	span   diagnostics.Span
}

// qualified is the enum's database identity: two enums are the same
// type exactly when this agrees.
func (e *enumType) qualified() string { return e.schema + "." + e.name }

// resolveType maps a described type to its Go type: the dialect's
// static TypeMap first, then a user-defined enum (design 26 §4.3). ok
// is false only when neither applies — the caller's SQLETCH311. An enum
// whose Go name is unusable or taken by a different enum is reported
// in diags (SQLETCH307/310) with ok still true, so the caller does not
// add a misleading SQLETCH311 on top.
func (g *queryGen) resolveType(tr dialect.TypeRef) (ref dialect.GoTypeRef, ok bool, diags []diagnostics.Diagnostic) {
	if ref, ok := g.tm.GoType(tr.OID); ok {
		return ref, true, nil
	}
	if !tr.IsEnum() {
		return dialect.GoTypeRef{}, false, nil
	}
	q := g.in.Q
	goName := enumGoName(tr.Name)
	if !token.IsIdentifier(goName) || !token.IsExported(goName) {
		return dialect.GoTypeRef{}, true, []diagnostics.Diagnostic{diagnostics.Errorf(diagnostics.CodeInvalidColumnIdentifier, q.HeaderSpan,
			"enum %s.%s maps to Go type name %q, which is not a valid exported identifier", tr.Ext.Schema, tr.Name, goName).
			WithHint("bind and read it through text instead: CAST(:param AS text)::%s, and %s::text in a projection", tr.Name, tr.Name)}
	}
	if prev, ok := g.enums[goName]; ok {
		if prev.schema != tr.Ext.Schema || prev.name != tr.Name {
			return dialect.GoTypeRef{}, true, []diagnostics.Diagnostic{diagnostics.Errorf(diagnostics.CodeNameCollision, q.HeaderSpan,
				"enums %s (query %s) and %s.%s (query %s) both generate Go type %q; rename one of the types",
				prev.qualified(), prev.query, tr.Ext.Schema, tr.Name, q.Name, goName)}
		}
		return dialect.GoTypeRef{Name: goName}, true, nil
	}
	g.enums[goName] = &enumType{
		goName: goName, schema: tr.Ext.Schema, name: tr.Name, labels: tr.Ext.Labels,
		query: q.Name, span: q.HeaderSpan,
	}
	return dialect.GoTypeRef{Name: goName}, true, nil
}

// enumGoName is an enum type's Go name: GoName over the type name with
// every rune that cannot occur in a Go identifier acting as a word
// break (a quoted type name may contain anything).
func enumGoName(typname string) string {
	return GoName(identWords(typname))
}

// enumConstNames names each label's constant, typeName + label. ok is
// false when some label has no letter or digit at all, or two labels
// land on one name (`in-progress` / `in_progress`; `a` / `A`) — design
// 26 D2: the type is still emitted, without constants, and the caller
// warns.
func enumConstNames(typeName string, labels []string) (names []string, bad []string) {
	seen := map[string]string{}
	for _, l := range labels {
		w := identWords(l)
		if strings.Trim(w, "_") == "" {
			bad = append(bad, l)
			continue
		}
		suffix := GoName(w)
		// GoName prefixes "X" when the first rune is not a letter; the
		// type-name prefix already makes the constant a valid
		// identifier, and the X would make `1st` and `x1st` collide.
		if r := []rune(strings.TrimLeft(w, "_")); !unicode.IsLetter(r[0]) {
			suffix = strings.TrimPrefix(suffix, "X")
		}
		name := typeName + suffix
		if prev, dup := seen[name]; dup {
			bad = append(bad, prev, l)
			continue
		}
		seen[name] = l
		names = append(names, name)
	}
	if len(bad) > 0 {
		return nil, bad
	}
	return names, nil
}

// identWords replaces every rune that cannot appear in a Go identifier
// with '_', GoName's word separator.
func identWords(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, s)
}

// enumsFile emits enums.gen.go: every referenced enum, sorted by Go
// name. constNames carries each enum's constant names (nil = none, D2).
func enumsFile(pkg string, enums map[string]*enumType, constNames map[string][]string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by sqletch. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	for _, tn := range sortedKeys(enums) {
		e := enums[tn]
		fmt.Fprintf(&b, "// %s is the database enum %s. Its values are the enum's labels;\n", tn, e.qualified())
		fmt.Fprint(&b, "// the database rejects any other value when it is bound.\n")
		fmt.Fprintf(&b, "type %s string\n\n", tn)
		names := constNames[tn]
		if names == nil {
			fmt.Fprintf(&b, "// No constants for %s: its labels do not map to distinct Go\n", tn)
			fmt.Fprint(&b, "// identifiers (SQLETCH320). Convert the label text: "+tn+"(\"…\").\n\n")
			continue
		}
		fmt.Fprint(&b, "const (\n")
		for i, l := range e.labels {
			fmt.Fprintf(&b, "\t%s %s = %q\n", names[i], tn, l)
		}
		fmt.Fprint(&b, ")\n\n")
	}
	return b.String()
}

// checkEnumNames runs after every query has registered its names: an
// enum is declared once for the package, so a per-query claimType
// cannot see it. Every enum type and constant name must be new at
// package level — not a generated fixed name (SQLETCH307), a query's
// type or @choose/@order-by constant, a policy type, or another enum's
// name (SQLETCH310). It returns each enum's constant names; an enum
// whose labels do not give distinct identifiers gets none and a
// SQLETCH320 warning (design 26 D2). Sorted throughout: diagnostics
// may not depend on map order.
func checkEnumNames(enums map[string]*enumType, typeNames map[string]string,
	policyTypes map[string]*policyType, pkgConsts map[string]string) (map[string][]string, []diagnostics.Diagnostic) {

	var diags []diagnostics.Diagnostic
	owner := map[string]string{} // package-level identifier -> who declares it
	for _, n := range sortedKeys(typeNames) {
		owner[n] = "query " + typeNames[n]
	}
	for _, n := range sortedKeys(pkgConsts) {
		if _, ok := owner[n]; !ok {
			owner[n] = "query " + pkgConsts[n]
		}
	}
	for _, n := range sortedKeys(policyTypes) {
		if _, ok := owner[n]; !ok {
			owner[n] = fmt.Sprintf("policy parameter %q", policyTypes[n].param)
		}
	}
	claim := func(e *enumType, ident string) bool {
		if generatedPkgNames[ident] {
			diags = append(diags, diagnostics.Errorf(diagnostics.CodeInvalidColumnIdentifier, e.span,
				"enum %s generates the name %q, which the generated package already declares at package level; rename the type",
				e.qualified(), ident))
			return false
		}
		if prev, ok := owner[ident]; ok {
			diags = append(diags, diagnostics.Errorf(diagnostics.CodeNameCollision, e.span,
				"enum %s generates the name %q, which %s also generates; rename one",
				e.qualified(), ident, prev))
			return false
		}
		owner[ident] = "enum " + e.qualified()
		return true
	}

	consts := map[string][]string{}
	for _, tn := range sortedKeys(enums) {
		claim(enums[tn], tn)
	}
	for _, tn := range sortedKeys(enums) {
		e := enums[tn]
		names, bad := enumConstNames(tn, e.labels)
		if bad != nil {
			diags = append(diags, diagnostics.Warnf(diagnostics.CodeEnumLabelIdent, e.span,
				"labels %s of enum %s do not map to distinct Go identifiers; %s is generated without constants",
				quoteAll(bad), e.qualified(), tn))
			continue
		}
		for _, n := range names {
			claim(e, n)
		}
		consts[tn] = names
	}
	return consts, diags
}

// quoteAll renders labels for a diagnostic, deduplicated in first-seen
// order.
func quoteAll(labels []string) string {
	seen := map[string]bool{}
	var out []string
	for _, l := range labels {
		if !seen[l] {
			seen[l] = true
			out = append(out, fmt.Sprintf("%q", l))
		}
	}
	return strings.Join(out, ", ")
}

// The MySQL profile's identifier folds (internal/dialect/mysql/
// identfold.go) are derived from the server, never from Go's Unicode
// tables. This re-derives utf8mb3_general_ci's lower-case mapping for
// every non-ASCII BMP code point from a live server and compares it with
// the committed table; SQLETCH_UPDATE_IDENTFOLD=1 rewrites the table.
func TestMySQLIdentFoldTableMatchesServer(t *testing.T) {
	conn, _ := acquireMySQL(t)
	if _, err := conn.Execute("SET SESSION cte_max_recursion_depth = 70000"); err != nil {
		t.Fatal(err)
	}
	// HEX comparison: a plain `<>` would compare under a case-insensitive
	// collation and hide almost every mapping.
	res, err := conn.Execute(`
WITH RECURSIVE n(cp) AS (SELECT 128 UNION ALL SELECT cp + 1 FROM n WHERE cp < 65535),
m AS (
  SELECT cp,
         HEX(CONVERT(CHAR(cp USING utf32) USING utf8mb3)) AS orig,
         HEX(LOWER(CONVERT(CHAR(cp USING utf32) USING utf8mb3) COLLATE utf8mb3_general_ci)) AS low,
         CONV(HEX(CONVERT(LOWER(CONVERT(CHAR(cp USING utf32) USING utf8mb3) COLLATE utf8mb3_general_ci) USING utf32)), 16, 10) AS lowcp
  FROM n WHERE cp NOT BETWEEN 55296 AND 57343)
SELECT cp, lowcp FROM m WHERE orig <> low ORDER BY cp`)
	if err != nil {
		t.Fatal(err)
	}
	var server [][2]rune
	for r := range res.Resultset.RowDatas {
		from, err := res.GetInt(r, 0)
		if err != nil {
			t.Fatal(err)
		}
		to, err := res.GetInt(r, 1)
		if err != nil {
			t.Fatal(err)
		}
		server = append(server, [2]rune{rune(from), rune(to)})
	}
	if len(server) < 600 {
		t.Fatalf("only %d mappings derived; the extraction query is broken", len(server))
	}
	if os.Getenv("SQLETCH_UPDATE_IDENTFOLD") == "1" {
		writeIdentFoldTable(t, server)
		return
	}
	if committed := mysql.IdentLowerPairs(); !slices.Equal(committed, server) {
		t.Fatalf("committed identifier fold table (%d pairs) differs from the server's (%d pairs); rerun with SQLETCH_UPDATE_IDENTFOLD=1", len(committed), len(server))
	}
}

func writeIdentFoldTable(t *testing.T, pairs [][2]rune) {
	t.Helper()
	_, self, _, _ := runtime.Caller(0)
	path := filepath.Join(filepath.Dir(self), "..", "dialect", "mysql", "identfold_table.go")
	var b strings.Builder
	b.WriteString("// Code generated by TestMySQLIdentFoldTableMatchesServer (SQLETCH_UPDATE_IDENTFOLD=1); DO NOT EDIT.\n\n")
	b.WriteString("package mysql\n\n")
	b.WriteString("// identLowerPairs is utf8mb3_general_ci's lower-case mapping for every\n")
	b.WriteString("// non-ASCII BMP code point it changes, extracted from a MySQL server.\n")
	b.WriteString("var identLowerPairs = [...][2]rune{\n")
	for _, p := range pairs {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", p[0], p[1])
	}
	b.WriteString("}\n")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

// The server's comparison semantics the folds model, pinned both ways:
// every pair the server treats as one column must share FoldColumn's
// key and every pair it keeps apart must not; relation names compare
// exactly on this server (lower_case_table_names=0), which the "must"
// key reproduces, while the "may" key still joins them.
func TestMySQLIdentFoldSemanticsMatchServer(t *testing.T) {
	conn, _ := acquireMySQL(t)
	exec := func(q string) error { _, err := conn.Execute(q); return err }
	if err := exec("DROP TABLE IF EXISTS fold_t, `fold_T`"); err != nil {
		t.Fatal(err)
	}
	cols := []string{"x", "é", "kelvin", "ß", "i", "ǅ", "ﬀ", "ƀ"}
	var defs []string
	for _, c := range cols {
		defs = append(defs, "`"+c+"` INT")
	}
	if err := exec("CREATE TABLE fold_t (" + strings.Join(defs, ", ") + ")"); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = exec("DROP TABLE IF EXISTS fold_t, `fold_T`") })
	fold := dialect.ColumnFold(mysql.Profile{})
	for _, tc := range []struct {
		ref, col string
		same     bool
	}{
		{"X", "x", true}, {"É", "é", true}, {"Kelvin", "kelvin", true}, {"KELVIN", "kelvin", true},
		{"İ", "i", true}, {"I", "i", true}, {"Ǆ", "ǅ", true}, {"ǆ", "ǅ", true},
		{"ẞ", "ß", false}, {"ss", "ß", false}, {"ı", "i", false}, {"ff", "ﬀ", false}, {"ｘ", "x", false}, {"e", "é", false},
		{"Ƀ", "ƀ", false}, // Go's ToLower merges these; the server does not
	} {
		err := exec("SELECT `" + tc.ref + "` FROM fold_t")
		if (err == nil) != tc.same {
			t.Errorf("server: `%s` resolving to column `%s` = %v, want %v (err %v)", tc.ref, tc.col, err == nil, tc.same, err)
		}
		if (fold(tc.ref) == fold(tc.col)) != tc.same {
			t.Errorf("FoldColumn: %q vs %q equal = %v, want %v", tc.ref, tc.col, !tc.same, tc.same)
		}
	}

	may, must := dialect.RelationFolds(mysql.Profile{})
	for _, tc := range []struct{ q, ref, rel string }{
		{"SELECT A.x FROM fold_t AS a", "A", "a"},
		{"SELECT É.x FROM fold_t AS é", "É", "é"},
		{"SELECT x FROM FOLD_T", "FOLD_T", "fold_t"},
	} {
		if err := exec(tc.q); err == nil {
			t.Errorf("server resolved %q although relation names are case-sensitive here", tc.q)
		}
		if must(tc.ref) == must(tc.rel) {
			t.Errorf("must key joins %q and %q, which this server keeps apart", tc.ref, tc.rel)
		}
		if may(tc.ref) != may(tc.rel) {
			t.Errorf("may key separates %q and %q, which lower_case_table_names=1 joins", tc.ref, tc.rel)
		}
	}
}

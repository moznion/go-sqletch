package cli

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/moznion/go-sqletch/internal/config"
	"github.com/moznion/go-sqletch/internal/diagnostics"
)

// Derived output (.sqletch/expanded/…) lives under the cache path's
// PARENT directory, but only cache.path and its ancestors are
// symlink-checked at config load (SQLETCH306). Every component BELOW
// the cache parent is repo-controlled — a cloned repository can commit
// `.sqletch/expanded -> /somewhere` — and os.RemoveAll/MkdirAll resolve
// such parents, which turned "replace the expansion directory" into a
// recursive delete outside the project (CWE-59).
//
// The helpers here close that in two layers:
//   - every existing component below the derived root is Lstat'ed and a
//     symlink (wherever it points) is refused as SQLETCH306 — nothing in
//     derived output is ever followed;
//   - the operations themselves run through an os.Root opened at the
//     derived root, so a symlink swapped in after the check still
//     cannot make them escape (it fails instead).

// errDerivedSymlink reports a symlinked component inside derived output.
type errDerivedSymlink struct{ rel string }

func (e *errDerivedSymlink) Error() string {
	return fmt.Sprintf("%s is a symlink", e.rel)
}

// derivedRootDir is the directory derived output is written relative to:
// the cache path's parent (the directory pathEscapeDiags already vetted
// as part of cache.path's ancestry).
func derivedRootDir(cfg config.Config) string {
	return cfg.Abs(filepath.Dir(cfg.Cache.Path))
}

// refuseSymlinks Lstats every existing component of rel (a path
// relative to root) and reports the first symlink. A missing component
// ends the walk: nothing below it exists.
func refuseSymlinks(root *os.Root, rel string) error {
	cur := ""
	for part := range strings.SplitSeq(filepath.Clean(rel), string(filepath.Separator)) {
		cur = filepath.Join(cur, part)
		fi, err := root.Lstat(cur)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if fi.Mode()&fs.ModeSymlink != 0 {
			return &errDerivedSymlink{rel: cur}
		}
	}
	return nil
}

// replaceDerivedDir makes rel (relative to the derived root) a fresh
// directory holding exactly files (name -> content). A symlinked
// component is a SQLETCH306 diagnostic and nothing is touched; any other
// failure — including os.Root refusing an escape — is an error.
func replaceDerivedDir(cfg config.Config, rel string, files map[string][]byte) (*diagnostics.Diagnostic, error) {
	rootDir := derivedRootDir(cfg)
	if err := os.MkdirAll(rootDir, 0o755); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(rootDir)
	if err != nil {
		return nil, err
	}
	defer func() { _ = root.Close() }()

	var sl *errDerivedSymlink
	if err := refuseSymlinks(root, rel); errors.As(err, &sl) {
		d := diagnostics.Errorf(diagnostics.CodePathEscape, diagnostics.Span{File: cfg.Path},
			"derived output path %q contains a symlink (%s): sqletch replaces this directory wholesale, so a committed symlink could redirect that delete-and-rewrite outside the project",
			filepath.ToSlash(filepath.Join(rootDir, rel)), filepath.ToSlash(filepath.Join(rootDir, sl.rel))).
			WithHint("remove the symlink; derived output under %s is regenerated by `sqletch generate` and never needs one", filepath.ToSlash(rootDir))
		return &d, nil
	} else if err != nil {
		return nil, err
	}
	if err := root.RemoveAll(rel); err != nil {
		return nil, err
	}
	if err := root.MkdirAll(rel, 0o755); err != nil {
		return nil, err
	}
	for name, data := range files {
		if err := root.WriteFile(filepath.Join(rel, name), data, 0o644); err != nil {
			return nil, err
		}
	}
	return nil, nil
}

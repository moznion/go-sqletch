package cli

import (
	"crypto/rand"
	"errors"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/moznion/go-sqletch/internal/config"
	"github.com/moznion/go-sqletch/internal/diagnostics"
)

// explainWriter writes the derived `explain/<slug>/<query>.json` tree
// without ever following a symlink a cloned repository committed into
// it (security finding F5, CWE-59).
//
// The slug comes from the repo-controlled output.path, and the tree
// lives next to the committed cache, so `.sqletch/explain/r -> /` plus
// `output.path: r/home/runner/.docker` would otherwise let a plain
// `sqletch generate` atomically replace `/home/runner/.docker/config.json`:
// MkdirAll and cache.WriteFileAtomic both follow an intermediate
// directory link (the latter only guards the leaf and its temp name).
//
// Two layers:
//   - every existing component between the anchor and the destination
//     directory is Lstat'ed; a symlink anywhere refuses that write with
//     SQLETCH306 — no silent follow, not even to a target inside the
//     project, because the explain tree is sqletch-owned output;
//   - the write itself goes through an os.Root at the anchor, so a link
//     swapped in after the check still cannot carry it outside.
//
// The anchor is the project directory when the cache (hence explain/)
// lives inside it — so a linked `.sqletch` is caught too — and the
// cache's parent directory for a deliberately absolute, out-of-project
// cache.path (an operator choice, design 07 §1).
type explainWriter struct {
	cfg     config.Config
	root    *os.Root
	base    string // explain/ relative to root, slash-separated
	diags   []diagnostics.Diagnostic
	refused map[string]bool
}

func openExplainWriter(cfg config.Config) (*explainWriter, error) {
	explainAbs := filepath.Join(filepath.Dir(cfg.Abs(cfg.Cache.Path)), "explain")
	anchor := filepath.Dir(explainAbs)
	if !outsideProject(cfg, cfg.Cache.Path) {
		anchor = cfg.Dir
	}
	rel, err := filepath.Rel(anchor, explainAbs)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(anchor, 0o755); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(anchor)
	if err != nil {
		return nil, err
	}
	return &explainWriter{cfg: cfg, root: root, base: filepath.ToSlash(rel), refused: map[string]bool{}}, nil
}

func (w *explainWriter) close() { _ = w.root.Close() }

// write stores data at explain/<slug>/<name>, or records SQLETCH306 and
// skips it when a component of the destination directory is a symlink.
func (w *explainWriter) write(slug, name string, data []byte) error {
	dir := path.Join(w.base, slug)
	link, err := w.firstSymlink(dir)
	if err != nil {
		return err
	}
	if link != "" {
		if !w.refused[link] {
			w.refused[link] = true
			w.diags = append(w.diags, diagnostics.Errorf(diagnostics.CodePathEscape,
				diagnostics.Span{File: w.cfg.Path},
				"%s is a symlink, so explain data is not written through it: sqletch does not follow links inside the derived-output tree it owns",
				filepath.Join(w.root.Name(), filepath.FromSlash(link))).
				WithHint("delete the symlink (the explain tree is regenerated by `sqletch generate`) and run again"))
		}
		return nil
	}
	if err := w.root.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return w.writeAtomic(path.Join(dir, name), data)
}

// firstSymlink returns the first existing component of dir (relative to
// the root, slash-separated) that is a symlink, or "" if none is. A
// missing component ends the walk: MkdirAll creates the rest as real
// directories.
func (w *explainWriter) firstSymlink(dir string) (string, error) {
	cur := ""
	for _, seg := range strings.Split(dir, "/") {
		if seg == "" || seg == "." {
			continue
		}
		cur = path.Join(cur, seg)
		fi, err := w.root.Lstat(cur)
		if errors.Is(err, fs.ErrNotExist) {
			return "", nil
		}
		if err != nil {
			return "", err
		}
		if fi.Mode()&fs.ModeSymlink != 0 {
			return cur, nil
		}
	}
	return "", nil
}

// writeAtomic is cache.WriteFileAtomic's discipline inside the root: an
// O_EXCL temp file with a random name, then a rename that replaces a
// link sitting at the leaf instead of writing through it.
func (w *explainWriter) writeAtomic(name string, data []byte) error {
	tmp := path.Join(path.Dir(name), "."+path.Base(name)+"."+rand.Text()+".tmp")
	f, err := w.root.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	done := false
	defer func() {
		if !done {
			_ = w.root.Remove(tmp)
		}
	}()
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Chmod(0o644); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := w.root.Rename(tmp, name); err != nil {
		return err
	}
	done = true
	return nil
}
